"""Write docs/email/email-list.md and docs/sms/sms-list.md from the catalogue.

    backend/api/.venv/bin/python docs/tools/generate-message-lists.py

Every email with its subject, To and Cc, and every text with its words, read
from `cmp.core.messages.CATALOGUE` so neither list can drift from what is
sent. The plan at the foot of each file is written here.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend" / "api" / "src"))

from cmp.core.messages import CATALOGUE, Channel, render_text  # noqa: E402

EMAIL_OUT = ROOT / "docs" / "email" / "email-list.md"
SMS_OUT = ROOT / "docs" / "sms" / "sms-list.md"


def cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", "<br>").strip()


def cc_of(j) -> str:
    if j.copyable:
        return "Allowed: the office's addresses (Message templates, Copy to) and `EMAIL_CC_ADDRESSES`"
    return "Never"


def emails() -> str:
    rows = [j for j in CATALOGUE if Channel.EMAIL in j.channels]
    copy = sum(1 for j in rows if j.copyable)
    out = [
        "# Every email the application sends",
        "",
        "[Email](README.md) · [Every text](../sms/sms-list.md) · [Wording in full](messages.md)",
        "",
        "Generated by `docs/tools/generate-message-lists.py` from the message catalogue",
        "(`backend/api/src/cmp/core/messages.py`). Do not edit by hand; run the tool.",
        "",
        f"**{len(rows)} emails. {copy} may be copied (Cc); {len(rows) - copy} never are.**",
        "",
        "- **From**, on every email: `<organisation> Privacy Office <SENDER_EMAIL>`, one address for the whole application.",
        "- **To**: one person per email. A message for several people is one email each.",
        "- **Cc**: only on emails about the work between the office, staff and holders. Never on an email carrying a code or a link, or one to a person about her own data (ADR 0029).",
        "- **Subject**: the default below, until the office replaces it in the console under **Message templates**. Words in `{braces}` are filled in when it is sent.",
        "- The console sends and manages all of them. The portal sends none itself; it is where the links in them open.",
        "",
    ]
    group = None
    n = 0
    for j in rows:
        if j.group != group:
            group = j.group
            out += [
                "",
                f"## {group}",
                "",
                "| # | Email | Subject | To | Cc | Also a text | File attached |",
                "|---|---|---|---|---|---|---|",
            ]
        n += 1
        out.append(
            f"| {n} | **{cell(j.title)}**<br>`{j.key.value}` | {cell(j.email_subject)} | {cell(j.to)} "
            f"| {cc_of(j)} | {'Yes' if Channel.SMS in j.channels else 'No'} | {cell(j.attachment) or 'None'} |"
        )
    out += ["", EMAIL_PLAN]
    return "\n".join(out) + "\n"


def sms() -> str:
    rows = [j for j in CATALOGUE if Channel.SMS in j.channels]
    out = [
        "# Every text (SMS) the application sends",
        "",
        "[Every email](../email/email-list.md) · [Texts through Amazon SNS](../decisions/0043-texts-go-through-amazon-sns-from-the-workers.md)",
        "",
        "Generated by `docs/tools/generate-message-lists.py` from the message catalogue",
        "(`backend/api/src/cmp/core/messages.py`). Do not edit by hand; run the tool.",
        "",
        f"**{len(rows)} texts.** Each is the short form of an email of the same name: a number gets the text, an address gets the email.",
        "",
        "- **To**: one mobile number per text. A text is never copied.",
        "- **Sender**: the gateway's sender ID (`SMS_SNS_SENDER_ID` or `SMS_HTTP_SENDER`). In India a sender ID works only after DLT registration.",
        "- **Words**: the default below, until the office replaces them in the console under **Message templates**. At most 480 characters (three parts).",
        "- **Length** is counted with the sample values the console preview uses; one part is 160 characters, then 153 each.",
        "",
    ]
    group = None
    n = 0
    for j in rows:
        if j.group != group:
            group = j.group
            out += [
                "",
                f"## {group}",
                "",
                "| # | Text | To | Template | Length | Parts |",
                "|---|---|---|---|---|---|",
            ]
        n += 1
        length = len(render_text(j.sms_body or "", j.samples))
        parts = 1 if length <= 160 else -(-length // 153)
        out.append(
            f"| {n} | **{cell(j.title)}**<br>`{j.key.value}` | {cell(j.to)} | {cell(j.sms_body)} | {length} | {parts} |"
        )
    out += ["", SMS_PLAN]
    return "\n".join(out) + "\n"


