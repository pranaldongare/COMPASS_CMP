def main() -> None:
    EMAIL_OUT.parent.mkdir(parents=True, exist_ok=True)
    SMS_OUT.parent.mkdir(parents=True, exist_ok=True)
    EMAIL_OUT.write_text(emails(), encoding="utf-8")
    SMS_OUT.write_text(sms(), encoding="utf-8")
    print(f"wrote {EMAIL_OUT.relative_to(ROOT)} and {SMS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
