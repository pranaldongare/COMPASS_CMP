"""Write docs/domain/analytics-metrics.md from the analytics catalogue (ADR 0045).

    backend/api/.venv/bin/python docs/tools/generate-analytics-docs.py [--check]

Every metric with its exact definition, unit, audience, breakdowns and default
target; every report kind with who may ask for it and in which formats; every
audit report with its events. Read from `cmp.core.metrics`, so the reference
cannot drift from what the screens and reports count. `--check` exits 1 when
the file is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend" / "api" / "src"))

from cmp.core import metrics as cat  # noqa: E402
from cmp.core.permissions import ROLE_TITLES  # noqa: E402

OUT = ROOT / "docs" / "domain" / "analytics-metrics.md"

SECTION_TITLES = {
    "management": "Management scorecard",
    "analytics": "Analytics",
    "mine": "Your work (the roles that do the work)",
    "health": "Platform health (the administrator)",
    "quality": "Data quality",
}
KINDS = {
    "count": "count of rows in the period",
    "median": "median over the period",
    "ratio": "rate of two counts",
    "snapshot": "as things stand now",
    "live": "read from the running service",
}


def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def roles(names: frozenset[str]) -> str:
    return ", ".join(ROLE_TITLES.get(r, r) for r in sorted(names))


def target(m: cat.Metric) -> str:
    if m.target is None:
        return "-"
    way = "at least" if m.higher_is_better else "at most"
    amber = f"; amber {m.amber:g}" if m.amber is not None else ""
    return f"{way} {m.target:g}{amber}"


def render() -> str:
    lines = [
        "# Analytics: every figure, report and audit report",
        "",
        "[ADR 0045](../decisions/0045-analytics-are-figures-counted-from-the-record.md) · "
        "[How the analytics work](analytics.md)",
        "",
        "Generated by `docs/tools/generate-analytics-docs.py` from `backend/api/src/cmp/core/"
        "metrics.py`. Do not edit by hand; run the tool.",
        "",
        f"**{len(cat.CATALOGUE)} metrics, {len(cat.REPORTS)} report kinds, "
        f"{len(cat.AUDIT_REPORTS)} audit reports.** A target is the default; the administrator "
        "may replace it in the console (Analytics, Settings). A metric marked *people* is "
        "withheld below the small-number threshold.",
    ]
    for section, title in SECTION_TITLES.items():
        mine = [m for m in cat.CATALOGUE if m.section == section]
        if not mine:
            continue
        lines += [
            "",
            f"## {title}",
            "",
            f"Read by: {roles(cat.SECTIONS[section])}.",
            "",
            "| Metric | Key | What it counts | Unit | How | Breakdowns | Default target | People |",
            "|---|---|---|---|---|---|---|---|",
        ]
        group = None
        for m in mine:
            name = f"**{cell(m.title)}**"
            if m.group != group:
                lines.append(f"| *{cell(m.group)}* | | | | | | | |")
                group = m.group
            how = KINDS[m.kind]
            if m.kind == "ratio":
                how += f": `{m.numerator}` / `{m.denominator}`"
            lines.append(
                f"| {name} | `{m.key}` | {cell(m.definition)} | {m.unit} | {how} | "
                f"{', '.join(cat.DIMENSIONS[d] for d in m.dims) or '-'} | {target(m)} | "
                f"{'yes' if m.people else ''} |"
            )
    lines += [
        "",
        "## Report kinds",
        "",
        "| Report | Key | What it holds | Who may ask for it | Formats | On a schedule |",
        "|---|---|---|---|---|---|",
    ]
    for r in cat.REPORTS.values():
        who = roles(r.audience) + (" (each their own)" if r.private else "")
        lines.append(
            f"| **{cell(r.title)}** | `{r.key}` | {cell(r.description)} | {who} | "
            f"{', '.join(r.formats)} | {'yes' if r.schedulable and not r.private else 'no'} |"
        )
    lines += [
        "",
        "## Audit reports",
        "",
        f"Read by: {roles(cat.AUDIT_READERS)} - each officer for their own office's rows.",
        "",
        "| Audit report | Key | What it lists | Events |",
        "|---|---|---|---|",
    ]
    for a in cat.AUDIT_REPORTS.values():
        lines.append(
            f"| **{cell(a.title)}** | `{a.key}` | {cell(a.description)} | "
            + ", ".join(f"`{e}`" for e in a.events)
            + " |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run the tool")
            return 1
        print("analytics reference is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cat.CATALOGUE)} metrics")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
